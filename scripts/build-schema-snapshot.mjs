/** Build supabase/schema-snapshot.sql from a live-catalog JSON dump.
 *
 *  Input: the JSON produced by scripts/schema-dump.sql (default path
 *  supabase/schema-dump.json — git-ignored; pass another path as argv[2]).
 *  Output: supabase/schema-snapshot.sql, the reference-only dump the gates
 *  read (check:schema parses `create table public.X (` blocks; check:freshness
 *  looks for created object names; check:realtime parses the publication
 *  block). The file is documentation, not a migration — objects are grouped
 *  by kind, not in dependency order, and grants/ACLs are comments.
 *
 *  Deterministic: the dump query pins ordering, and this script adds nothing
 *  time-dependent except the generation date in the header.
 *  Run: node scripts/build-schema-snapshot.mjs [path/to/dump.json] */
import { readFileSync, writeFileSync } from 'node:fs'

const inPath = process.argv[2] ?? 'supabase/schema-dump.json'
const outPath = 'supabase/schema-snapshot.sql'
const dump = JSON.parse(readFileSync(inPath, 'utf8'))

const RULE = '-- ============================================================'
const out = []
const section = (title) => { out.push(RULE, `-- ${title}`, RULE, '') }
const q = (s) => `'${String(s).replace(/'/g, "''")}'`

/* ---- header ---- */
out.push(
  RULE,
  '-- CID Portal — live schema snapshot (REFERENCE ONLY)',
  RULE,
  `-- Generated ${dump.generated_at ?? 'unknown date'} from the live Supabase project \`cid\``,
  '-- via scripts/schema-dump.sql (Postgres catalog queries) and',
  '-- scripts/build-schema-snapshot.mjs. Do not edit by hand: re-run the',
  '-- dump + build after applying migrations (see supabase/README.md).',
  '--',
  '-- This file is documentation, not a migration:',
  '--   * `supabase db reset` does NOT replay it (it lives outside',
  '--     migrations/), and it is not guaranteed to replay cleanly --',
  '--     objects are grouped by kind, not in dependency order.',
  '--   * The live project stays the source of truth.',
  '--   * The grants / ACL / realtime sections are informational',
  '--     comments, not executable statements.',
  '--',
  '-- Contents: enum types, tables (public + private), views, standalone',
  '-- indexes, functions, triggers, RLS policies, realtime publication',
  '-- members, table grants, column ACLs and function ACLs.',
)
out.push('')

/* ---- enums ---- */
section('Enum types')
for (const e of dump.enums ?? []) {
  out.push(`create type public.${e.name} as enum (${e.labels.map(q).join(', ')});`, '')
}

/* ---- tables ---- */
section('Tables (public + private), columns, constraints, RLS flags')
const constraintIndexNames = new Set()
for (const t of dump.tables ?? []) {
  const cols = (t.columns ?? []).map((c) => {
    let line = `  ${c.name} ${c.type}`
    if (c.generated === 's') line += ` generated always as (${c.default}) stored`
    else if (c.identity === 'a') line += ' generated always as identity'
    else if (c.identity === 'd') line += ' generated by default as identity'
    if (c.notnull) line += ' not null'
    if (c.default != null && c.generated !== 's') line += ` default ${c.default}`
    return line
  })
  out.push(`create table ${t.schema}.${t.name} (`, cols.join(',\n'), ');')
  for (const k of t.constraints ?? []) {
    out.push(`alter table ${t.schema}.${t.name} add constraint ${k.name} ${k.def};`)
    if (k.type === 'p' || k.type === 'u' || k.type === 'x') constraintIndexNames.add(`${t.name}.${k.name}`)
  }
  if (t.rls) out.push(`alter table ${t.schema}.${t.name} enable row level security;`)
  if (t.forced) out.push(`alter table ${t.schema}.${t.name} force row level security;`)
  out.push('')
}

/* ---- views ---- */
section('Views')
for (const v of dump.views ?? []) {
  out.push(`create or replace view public.${v.name} as`, v.def.trim(), '')
}

/* ---- indexes ---- */
section('Indexes (excluding those backing PK/unique constraints)')
for (const i of dump.indexes ?? []) {
  if (constraintIndexNames.has(`${i.table}.${i.name}`)) continue
  out.push(`${i.def};`)
}
out.push('')

/* ---- functions ---- */
section('Functions (public + private, non-extension)')
const fns = dump.functions ?? []
for (const schema of ['public', 'private']) {
  out.push(`-- ---- ${schema} ----`, '')
  for (const f of fns.filter((x) => x.schema === schema)) {
    out.push(f.def.trimEnd().replace(/\n$/, ''), ';', '')
  }
}

/* ---- triggers ---- */
section('Triggers (non-internal)')
for (const t of dump.triggers ?? []) out.push(`${t.def};`)
out.push('')

/* ---- policies ---- */
section('Row-Level Security policies')
for (const p of dump.policies ?? []) {
  const roles = (p.roles ?? []).join(', ')
  const cmd = String(p.cmd ?? 'ALL').toLowerCase()
  const mode = p.permissive === 'PERMISSIVE' ? 'permissive' : 'restrictive'
  out.push(`create policy ${p.name} on public.${p.table}`, `  as ${mode} for ${cmd} to ${roles}`)
  if (p.qual != null) out.push(`  using (${p.qual})`)
  if (p.with_check != null) out.push(`  with check (${p.with_check})`)
  out[out.length - 1] += ';'
  out.push('')
}

/* ---- realtime ---- */
section('Realtime publication members (supabase_realtime)')
out.push('--')
for (const t of dump.publication ?? []) out.push(`--   public.${t}`)
out.push('')

/* ---- grants ---- */
section('Table grants (anon / authenticated / service_role)')
out.push('--', '-- Informational. `anon` holds no table privileges (grant hygiene', '-- migration 20260908130000). One line per table and grantee.', '--')
const byTable = new Map()
for (const g of dump.grants ?? []) {
  if (!byTable.has(g.table)) byTable.set(g.table, [])
  byTable.get(g.table).push(`${g.grantee}: ${g.privs}`)
}
for (const [table, lines] of byTable) out.push(`--   ${table} -> ${lines.join(' | ')}`)
out.push('')

section('Column-level ACLs (columns with explicit column grants)')
out.push('--')
for (const c of dump.column_acl ?? []) out.push(`--   ${c.table}.${c.column}: ${c.acl}`)
out.push('')

section('Function ACLs (EXECUTE grants; null = default, i.e. PUBLIC)')
out.push('--')
for (const f of fns) out.push(`--   ${f.schema}.${f.name}(${f.args}): ${f.acl ?? 'default (PUBLIC)'}`)
out.push('')

writeFileSync(outPath, out.join('\n'))
const counts = {
  enums: (dump.enums ?? []).length, tables: (dump.tables ?? []).length, views: (dump.views ?? []).length,
  indexes: (dump.indexes ?? []).length, functions: fns.length, triggers: (dump.triggers ?? []).length,
  policies: (dump.policies ?? []).length, publication: (dump.publication ?? []).length,
}
console.log(`wrote ${outPath}:`, JSON.stringify(counts))
